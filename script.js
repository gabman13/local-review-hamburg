const defaultLanguage = "de";
const year = new Date().getFullYear();
const navToggle = document.querySelector(".nav-toggle");
const navLinks = document.querySelector(".nav-links");
const revealElements = document.querySelectorAll(".reveal");
const languageButtons = document.querySelectorAll(".language-button");

const getTranslation = (language, key) => {
  return key.split(".").reduce((value, part) => {
    if (Array.isArray(value)) {
      return value[Number(part)];
    }

    return value ? value[part] : undefined;
  }, translations[language]);
};

const setMeta = (selector, attribute, value) => {
  const element = document.querySelector(selector);

  if (element) {
    element.setAttribute(attribute, value);
  }
};

const applyLanguage = (language) => {
  const selectedLanguage = translations[language] ? language : defaultLanguage;
  const copy = translations[selectedLanguage];

  document.documentElement.lang = selectedLanguage;
  document.title = copy.meta.title;
  setMeta('meta[name="description"]', "content", copy.meta.description);
  setMeta('meta[property="og:title"]', "content", copy.meta.ogTitle);
  setMeta('meta[property="og:description"]', "content", copy.meta.ogDescription);

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const value = getTranslation(selectedLanguage, element.dataset.i18n);

    if (typeof value === "string") {
      if (element.dataset.i18n === "footer") {
        element.innerHTML = value.replace("{year}", year);
      } else {
        element.textContent = value;
      }
    }
  });

  document.querySelectorAll("[data-i18n-attr]").forEach((element) => {
    element.dataset.i18nAttr.split(",").forEach((pair) => {
      const [attribute, key] = pair.split(":");
      const value = getTranslation(selectedLanguage, key);

      if (attribute && typeof value === "string") {
        element.setAttribute(attribute, value);
      }
    });
  });

  languageButtons.forEach((button) => {
    const isActive = button.dataset.language === selectedLanguage;
    button.classList.toggle("active", isActive);
    button.setAttribute("aria-pressed", String(isActive));
  });

};

if (navToggle && navLinks) {
  navToggle.addEventListener("click", () => {
    const isOpen = navLinks.classList.toggle("open");
    navToggle.setAttribute("aria-expanded", String(isOpen));
  });

  navLinks.addEventListener("click", (event) => {
    if (event.target instanceof HTMLAnchorElement) {
      navLinks.classList.remove("open");
      navToggle.setAttribute("aria-expanded", "false");
    }
  });
}

languageButtons.forEach((button) => {
  button.addEventListener("click", () => {
    applyLanguage(button.dataset.language);
  });
});

const revealObserver = new IntersectionObserver(
  (entries) => {
    entries.forEach((entry) => {
      if (entry.isIntersecting) {
        entry.target.classList.add("visible");
        revealObserver.unobserve(entry.target);
      }
    });
  },
  { threshold: 0.14 }
);

revealElements.forEach((element) => revealObserver.observe(element));

applyLanguage(defaultLanguage);
